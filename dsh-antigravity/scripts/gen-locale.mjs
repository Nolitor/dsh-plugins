#!/usr/bin/env node
/**
 * Generate lib/locale-table.js from locale/en.json and locale/ko.json.
 *
 * The browser half cannot import JSON (the loader evaluates client.js as a plain
 * script), so the tables are baked into a generated module. Editing the JSON and
 * re-running this script is the only supported way to change a string, which
 * keeps locale/*.json the single source of truth.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const read = (name) => JSON.parse(readFileSync(join(root, 'locale', name), 'utf8'))

const en = read('en.json')
const ko = read('ko.json')
const missing = Object.keys(en).filter((key) => !(key in ko))
if (missing.length > 0) {
  console.error('gen-locale: ko.json is missing keys: ' + missing.join(', '))
  process.exit(1)
}

const out = `/**
 * GENERATED by scripts/gen-locale.mjs -- do not edit.
 * Source of truth: locale/en.json and locale/ko.json.
 */
export const LOCALES = ['en', 'ko']
export const I18N = ${JSON.stringify({ en, ko }, null, 2)}
`
writeFileSync(join(root, 'lib', 'locale-table.js'), out)
console.log('gen-locale: wrote lib/locale-table.js (' + Object.keys(en).length + ' keys)')
