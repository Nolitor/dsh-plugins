#!/usr/bin/env node
/**
 * Repo-wide implementation-uniqueness gate (`ARCHITECTURE-LAYERED.md` §6 #3,
 * follow-up **R6**).
 *
 * WHY THIS GATE EXISTS
 * §6 #3 measured five names — `mapDelta`, `numberOrNull`, `pickSession`,
 * `createCostStore`, `backoffDelay` — and recorded that two of them existed in
 * more than one place. The rule that was being violated is NOT "each name is
 * defined once in the repository": the architecture deliberately allows a
 * vendor to keep a same-named *thin wrapper*, so a naive
 * `grep -c 'function name' | assert == 1` is wrong for `createCostStore`, which
 * legitimately appears three times. The real invariant is:
 *
 *   1. each name has exactly ONE implementation, and it lives in the core layer
 *      (`lib/**`, excluding `vendor/`);
 *   2. a vendor (`vendor/<pkg>/**`) may define the same name ONLY as a thin
 *      wrapper that imports the core symbol and CALLS it — the accepted
 *      precedent is `vendor/deepinfra/lib/cost.js` `createCostStore`, which
 *      delegates to the core `createSharedStore`. A vendor must never carry a
 *      second copy of the body;
 *   3. the vendor set is MEASURED from `vendor/*​/package.json`, never
 *      hand-listed, so a fifth vendored package is covered without editing this
 *      gate (same technique as `test/plan-boundary.test.mjs`).
 *
 * Because rule 1 alone cannot distinguish the DeepInfra delegation from the
 * OpenCode re-implementation, this gate reads the vendor file's *imports* and
 * the definition's *body*: definition present + core import present + a call to
 * the imported binding is a wrapper; anything else is a second implementation.
 *
 * Generated artifacts (`lib/client.js`, `lib/client.src.js`,
 * `lib/locale-table.js`) are excluded from the definition count — they are
 * build output, not a second implementation — but a gated name appearing inside
 * one FAILS the gate rather than being ignored, so the exclusion cannot hide a
 * copy.
 *
 * Usage:
 *   node scripts/verify-uniqueness.mjs            # check the real tree
 *   node scripts/verify-uniqueness.mjs --json     # machine-readable result
 *
 * Exit codes: 0 clean, 1 gate failure, 2 the gate could not run (vacuity).
 */
import { readFileSync, readdirSync } from 'node:fs'
import { dirname, join, posix, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))

/**
 * The names the roadmap puts under the gate (`HANDOFF.md`, `ROADMAP.md` R6).
 * This list is the SUBJECT of the gate, not its measurement: the counts are
 * measured from the tree on every run.
 */
export const GATED_NAMES = Object.freeze([
  'mapDelta',
  'numberOrNull',
  'pickSession',
  'createCostStore',
  'backoffDelay',
])

/** Directories that are never implementation sources. */
const SKIP_DIRS = Object.freeze(['node_modules', '.git', 'docs', 'test', 'spec', 'locale', 'market', 'fixtures'])

/** A generated artifact announces itself in its header (measured, not listed). */
const GENERATED_MARKER = 'GENERATED by scripts/'

/**
 * Blank JS comments while KEEPING string/template contents.
 *
 * Same contract as `test/stream-boundary.test.mjs` `stripComments`: an
 * identifier is real only in code, but a definition cannot hide in a comment
 * either, so both directions stay honest.
 *
 * @param {string} source - file text.
 * @returns {string} the same length, comment characters replaced by spaces.
 */
export function stripComments(source) {
  const out = source.split('')
  const blank = (from, to) => {
    for (let i = from; i < to && i < out.length; i += 1) if (out[i] !== '\n') out[i] = ' '
  }
  let index = 0
  let quote = null
  while (index < source.length) {
    const char = source[index]
    const next = source[index + 1]
    if (quote !== null) {
      if (char === '\\') {
        index += 2
        continue
      }
      if (char === quote) quote = null
      index += 1
      continue
    }
    if (char === '"' || char === "'" || char === '`') {
      quote = char
      index += 1
      continue
    }
    if (char === '/' && next === '*') {
      const end = source.indexOf('*/', index + 2)
      const stop = end === -1 ? source.length : end + 2
      blank(index, stop)
      index = stop
      continue
    }
    if (char === '/' && next === '/') {
      let stop = index
      while (stop < source.length && source[stop] !== '\n') stop += 1
      blank(index, stop)
      index = stop
      continue
    }
    index += 1
  }
  return out.join('')
}

/**
 * Every definition of one name in comment-free source, with its line number.
 *
 * A definition is a `function`/`class` declaration or a `const`/`let`/`var`
 * binding to a function expression or arrow. An import binding, a re-export
 * (`export { name }`) and a call site are NOT definitions — that distinction is
 * the whole reason the vendor-wrapper rule can exist.
 *
 * @param {string} code - comment-free source.
 * @param {string} name - the identifier to look for.
 * @returns {{ name: string, kind: string, index: number, line: number }[]} matches.
 */
export function definitionsOf(code, name) {
  const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  const patterns = [
    ['function', new RegExp(`(?:^|\\n)[ \\t]*(?:export[ \\t]+)?(?:default[ \\t]+)?(?:async[ \\t]+)?function[ \\t]*\\*?[ \\t]*${escaped}[ \\t]*\\(`, 'g')],
    ['class', new RegExp(`(?:^|\\n)[ \\t]*(?:export[ \\t]+)?(?:default[ \\t]+)?class[ \\t]+${escaped}\\b`, 'g')],
    ['binding', new RegExp(`(?:^|\\n)[ \\t]*(?:export[ \\t]+)?(?:const|let|var)[ \\t]+${escaped}[ \\t]*=[ \\t]*(?:async\\b|function\\b|\\([^)]*\\)[ \\t]*=>|[A-Za-z0-9_$]+[ \\t]*=>)`, 'g')],
  ]
  const found = []
  for (const [kind, pattern] of patterns) {
    for (const match of code.matchAll(pattern)) {
      // The match may start with the newline it consumed; anchor on the name.
      const offset = match.index + match[0].indexOf(name)
      found.push({ name, kind, index: offset, line: code.slice(0, offset).split('\n').length })
    }
  }
  return found.sort((left, right) => left.index - right.index)
}

/**
 * Find the matching close of a bracketed run starting at `open`.
 *
 * String-aware over already comment-free code. `open` must point AT the opening
 * bracket; the returned index is the matching closer, or `code.length` when the
 * run never closes.
 *
 * @param {string} code - comment-free source.
 * @param {number} open - offset of the opening bracket.
 * @returns {number} offset of the matching close.
 */
function matchBracket(code, open) {
  const opener = code[open]
  const closer = opener === '(' ? ')' : opener === '{' ? '}' : opener === '[' ? ']' : null
  if (closer === null) return open
  let depth = 0
  let quote = null
  for (let scan = open; scan < code.length; scan += 1) {
    const char = code[scan]
    if (quote !== null) {
      if (char === '\\') {
        scan += 1
        continue
      }
      if (char === quote) quote = null
      continue
    }
    if (char === '"' || char === "'" || char === '`') {
      quote = char
      continue
    }
    if (char === opener) depth += 1
    else if (char === closer) {
      depth -= 1
      if (depth === 0) return scan
    }
  }
  return code.length
}

/**
 * Extract the body text of the definition that starts at `index`.
 *
 * The parameter list is skipped FIRST, because a destructured parameter
 * (`function createCostStore({ path } = {})`) puts a `{` before the real body —
 * taking the first brace would hand back the parameter list and make the
 * accepted DeepInfra delegation look like a re-implementation. A definition
 * whose body cannot be delimited (a one-line expression arrow) yields the rest
 * of its line, which is still enough to see whether the core symbol is called.
 *
 * @param {string} code - comment-free source.
 * @param {number} index - offset of the definition's name.
 * @returns {string} the body text (possibly empty).
 */
export function bodyOf(code, index) {
  const lineEnd = code.indexOf('\n', index) === -1 ? code.length : code.indexOf('\n', index)
  const paren = code.indexOf('(', index)
  let searchFrom = index
  if (paren !== -1 && paren <= lineEnd) searchFrom = matchBracket(code, paren) + 1
  const open = code.indexOf('{', searchFrom)
  if (open === -1) return code.slice(index, lineEnd)
  // An arrow body may be an expression rather than a block: `const f = (x) => g(x)`.
  const between = code.slice(searchFrom, open)
  if (between.includes('=>') && code.slice(open, open + 2) === '{' && !between.trim().endsWith('=>')) {
    const rest = code.indexOf('\n', open)
    const stop = rest === -1 ? code.length : rest
    return code.slice(open, stop)
  }
  return code.slice(open, matchBracket(code, open) + 1)
}

/**
 * Static `import { … } from '…'` bindings in comment-free source.
 *
 * @param {string} code - comment-free source.
 * @returns {{ imported: string, local: string, specifier: string }[]} bindings.
 */
export function importBindings(code) {
  const out = []
  for (const match of code.matchAll(/\bimport\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"]/g)) {
    const specifier = match[2]
    for (const part of match[1].split(',')) {
      const entry = part.trim()
      if (entry.length === 0) continue
      const [imported, local] = entry.split(/\s+as\s+/).map((piece) => piece.trim())
      out.push({ imported, local: local ?? imported, specifier })
    }
  }
  return out
}

/**
 * Does this import specifier reach the CORE layer (`lib/**`)?
 *
 * Accepts a relative path that normalises into `lib/`, and the published bare
 * subpath (`@nolit/dsh-custom-router/…`), which the package `exports` map points
 * at `lib/`.
 *
 * @param {string} fromFile - posix path of the importing file, repo-relative.
 * @param {string} specifier - the import specifier.
 * @returns {boolean} true when it resolves into the core layer.
 */
export function reachesCore(fromFile, specifier) {
  if (specifier.startsWith('@nolit/dsh-custom-router')) return true
  if (!specifier.startsWith('.')) return false
  const resolved = posix.normalize(posix.join(posix.dirname(fromFile), specifier))
  return resolved.startsWith('lib/') || resolved === 'lib'
}

/** Repo-relative POSIX path of a path relative to the repo root. */
function toPosix(root, absolute) {
  return relative(root, absolute).split('\\').join('/')
}

/**
 * Every `.js`/`.mjs`/`.cjs` file under `dir`, repo-relative posix paths.
 * @param {string} root - repo root.
 * @param {string} dir - directory to walk.
 * @returns {string[]} sorted paths.
 */
export function walkSources(root, dir) {
  const out = []
  const visit = (absolute) => {
    for (const entry of readdirSync(absolute, { withFileTypes: true })) {
      if (entry.isDirectory()) {
        if (SKIP_DIRS.includes(entry.name)) continue
        visit(join(absolute, entry.name))
      } else if (/\.(?:js|mjs|cjs)$/.test(entry.name)) {
        out.push(toPosix(root, join(absolute, entry.name)))
      }
    }
  }
  visit(dir)
  return out.sort()
}

/**
 * The vendor set, MEASURED from `vendor/*​/package.json` (never hand-listed).
 *
 * @param {string} root - repo root.
 * @returns {{ dir: string, name: string }[]} one entry per vendored package.
 */
export function measuredVendors(root) {
  const vendorRoot = join(root, 'vendor')
  let entries
  try {
    entries = readdirSync(vendorRoot, { withFileTypes: true })
  } catch {
    return []
  }
  const out = []
  for (const entry of entries) {
    if (!entry.isDirectory()) continue
    let name
    try {
      name = JSON.parse(readFileSync(join(vendorRoot, entry.name, 'package.json'), 'utf8')).name
    } catch {
      continue
    }
    if (typeof name !== 'string' || name.length === 0) continue
    out.push({ dir: `vendor/${entry.name}`, name })
  }
  return out.sort((left, right) => left.dir.localeCompare(right.dir))
}

/**
 * Read the whole tree into `{ repoRelativePath → source }` plus the measured
 * vendor set and the measured generated-artifact set.
 *
 * The scan covers the WHOLE repository, not just `lib/` + `vendor/`: a definition
 * parked in `scripts/` or a build output would otherwise be invisible, and "one
 * implementation repo-wide" has to mean repo-wide. Test files are skipped
 * because a test legitimately defines a throwaway fixture, and `docs`/`market`/
 * `spec`/`locale` carry no implementation JS.
 *
 * @param {string} root - repo root.
 * @param {string[]} [roots] - top-level directories to include, default the two
 *   layers the rule names plus `scripts` and `bin`.
 * @returns {{ sources: Record<string, string>, vendors: {dir: string, name: string}[], generated: string[] }} the measured tree.
 */
export function collectTree(root, roots = ['lib', 'vendor', 'scripts', 'bin']) {
  const sources = {}
  for (const sub of roots) {
    let dir
    try {
      dir = join(root, sub)
      readdirSync(dir)
    } catch {
      continue
    }
    for (const file of walkSources(root, dir)) sources[file] = readFileSync(join(root, file), 'utf8')
  }
  const generated = Object.entries(sources)
    .filter(([, text]) => text.slice(0, 400).includes(GENERATED_MARKER))
    .map(([file]) => file)
    .sort()
  return { sources, vendors: measuredVendors(root), generated }
}

/** Is this repo path inside the core layer? */
function isCore(file) {
  return file.startsWith('lib/')
}

/** Is this repo path inside a measured vendor directory? */
function vendorOf(file, vendors) {
  return vendors.find((vendor) => file === vendor.dir || file.startsWith(`${vendor.dir}/`)) ?? null
}

/**
 * Scan one tree for uniqueness violations.
 *
 * Pure: takes the measured sources and returns findings, so a test can hand it a
 * doctored copy and prove each rule fires. Nothing is read here.
 *
 * @param {{ sources: Record<string, string>, vendors: {dir: string, name: string}[], generated?: string[] }} tree - measured tree.
 * @param {{ names?: readonly string[] }} [options] - name-set override for the negative proof.
 * @returns {{ name: string, rule: string, file: string, line: number, message: string }[]} findings, empty when clean.
 */
export function scanUniqueness(tree, options = {}) {
  const names = options.names ?? GATED_NAMES
  const generated = new Set(tree.generated ?? [])
  const findings = []
  const add = (name, rule, file, line, message) => findings.push({ name, rule, file, line, message })

  const files = Object.keys(tree.sources).sort()
  const codeOf = (file) => stripComments(tree.sources[file])

  for (const name of names) {
    const core = []
    const vendor = []
    const stray = []
    for (const file of files) {
      if (generated.has(file)) continue
      const code = codeOf(file)
      for (const definition of definitionsOf(code, name)) {
        if (isCore(file)) core.push({ file, ...definition, code })
        else if (vendorOf(file, tree.vendors) !== null) vendor.push({ file, ...definition, code })
        else stray.push({ file, ...definition })
      }
    }

    // Rule 0: a gated name inside a generated artifact is a copy, never build
    // output. The definition count ignores generated files, so this is the
    // guard that keeps that exclusion from hiding anything.
    for (const file of generated) {
      if (new RegExp(`\\b${name}\\b`).test(codeOf(file))) {
        add(name, 'generated-artifact', file, 0, `gated name "${name}" appears in a generated artifact`)
      }
    }

    // Rule 1: exactly one implementation, in the core layer.
    if (core.length !== 1) {
      const where = core.map((entry) => `${entry.file}:${entry.line}`).join(', ')
      add(name, 'core-count', 'lib', 0, `"${name}" has ${core.length} core definitions [${where}] — exactly one is required`)
    }

    // Rule 1b: a definition outside BOTH layers is a stray second copy. It is
    // neither the one core implementation nor an allowed vendor wrapper.
    for (const entry of stray) {
      add(name, 'stray-definition', entry.file, entry.line, `"${name}" is defined outside the core and vendor layers — the one implementation must live in lib/**`)
    }

    // Rule 2: a vendor definition must be a thin wrapper (import + call).
    for (const entry of vendor) {
      const bindings = importBindings(entry.code)
      const coreBindings = bindings.filter((binding) => binding.imported === name && reachesCore(entry.file, binding.specifier))
      if (coreBindings.length === 0) {
        const why = bindings.length === 0 ? 'it imports nothing' : `its imports [${bindings.map((binding) => `${binding.imported} from ${binding.specifier}`).join(', ')}] never bind the core "${name}"`
        add(name, 'vendor-reimplementation', entry.file, entry.line, `vendor re-implements "${name}": ${why} — a wrapper must import the core symbol and call it`)
        continue
      }
      const body = bodyOf(entry.code, entry.index)
      const called = coreBindings.find((binding) => new RegExp(`\\b${binding.local.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*\\(`).test(body))
      if (called === undefined) {
        add(name, 'vendor-reimplementation', entry.file, entry.line, `vendor defines "${name}" but never CALLS the core binding [${coreBindings.map((binding) => binding.local).join(', ')}] — a wrapper must delegate, not re-implement`)
      }
    }
  }
  return findings
}

/**
 * Run the gate over the real tree.
 * @param {string} root - repo root.
 * @returns {{ findings: object[], checked: object, vendors: object[], generated: string[] }} verdict.
 */
export function checkUniqueness(root) {
  const tree = collectTree(root)
  const findings = scanUniqueness(tree)
  const generated = new Set(tree.generated)
  const names = {}
  for (const name of GATED_NAMES) {
    const counts = { core: 0, vendor: 0, other: 0, total: 0 }
    for (const [file, text] of Object.entries(tree.sources)) {
      if (generated.has(file)) continue
      const code = stripComments(text)
      const found = definitionsOf(code, name).length
      if (found === 0) continue
      counts.total += found
      if (isCore(file)) counts.core += found
      else if (vendorOf(file, tree.vendors) !== null) counts.vendor += found
      else counts.other += found
    }
    names[name] = counts
  }
  return {
    findings,
    checked: { names, files: Object.keys(tree.sources).length },
    vendors: tree.vendors,
    generated: tree.generated,
  }
}

/** CLI. */
if (process.argv[1] !== undefined && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  let verdict
  try {
    verdict = checkUniqueness(ROOT)
  } catch (error) {
    process.stderr.write(`verify-uniqueness: cannot run — ${error instanceof Error ? error.message : String(error)}\n`)
    process.exit(2)
  }
  // Vacuity guard: an empty scan must not report success.
  if (verdict.checked.files === 0 || verdict.vendors.length === 0) {
    process.stderr.write(`verify-uniqueness: vacuous scan — ${verdict.checked.files} files, ${verdict.vendors.length} vendors\n`)
    process.exit(2)
  }
  if (process.argv.includes('--json')) {
    process.stdout.write(`${JSON.stringify(verdict, null, 2)}\n`)
  } else {
    for (const name of GATED_NAMES) {
      const counts = verdict.checked.names[name]
      const other = counts.other === 0 ? '' : ` other=${counts.other}`
      process.stdout.write(`${name.padEnd(16)} core=${counts.core} vendor=${counts.vendor}${other} total=${counts.total}\n`)
    }
    process.stdout.write(`\nvendors (measured from vendor/*/package.json): ${verdict.vendors.map((vendor) => `${vendor.dir} (${vendor.name})`).join(', ')}\n`)
    process.stdout.write(`generated artifacts excluded from the definition count: ${verdict.generated.join(', ')}\n`)
  }
  if (verdict.findings.length === 0) {
    process.stdout.write('\nverify-uniqueness: clean\n')
    process.exit(0)
  }
  process.stderr.write(`\nverify-uniqueness: ${verdict.findings.length} violation(s)\n`)
  for (const finding of verdict.findings) {
    process.stderr.write(`  [${finding.rule}] ${finding.file}${finding.line > 0 ? `:${finding.line}` : ''} — ${finding.message}\n`)
  }
  process.exit(1)
}
