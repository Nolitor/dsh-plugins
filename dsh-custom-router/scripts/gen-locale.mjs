#!/usr/bin/env node
/**
 * Generate lib/locale-table.js from locale/en.json, locale/ko.json and
 * locale/zh.json.
 *
 * The browser half cannot import JSON (the loader evaluates client.js as a
 * plain script), so the tables are baked into a generated module. Editing the
 * JSON and re-running this script is the only supported way to change a
 * string, which keeps locale/*.json the single source of truth.
 *
 * PARITY GATE: every locale must carry every key of the English table. A
 * half-translated dictionary would silently fall back to English at runtime,
 * so it fails here instead.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const LOCALES = ['en', 'ko', 'zh']
const read = (name) => JSON.parse(readFileSync(join(root, 'locale', name), 'utf8'))

const tables = {}
for (const locale of LOCALES) tables[locale] = read(locale + '.json')

const enKeys = Object.keys(tables.en)
if (enKeys.length === 0) {
  console.error('gen-locale: locale/en.json is empty')
  process.exit(1)
}
if (tables.en.meta === null || typeof tables.en.meta !== 'object') {
  console.error('gen-locale: locale/en.json is missing the nested meta object')
  process.exit(1)
}
for (const key of ['title', 'description']) {
  if (typeof tables.en.meta[key] !== 'string' || tables.en.meta[key].trim() === '') {
    console.error('gen-locale: locale/en.json meta.' + key + ' must be a non-empty string')
    process.exit(1)
  }
}
for (const locale of LOCALES) {
  if (tables[locale].meta === null || typeof tables[locale].meta !== 'object') {
    console.error('gen-locale: ' + locale + '.json is missing the nested meta object')
    process.exit(1)
  }
  for (const key of ['title', 'description']) {
    if (typeof tables[locale].meta[key] !== 'string' || tables[locale].meta[key].trim() === '') {
      console.error('gen-locale: ' + locale + '.json meta.' + key + ' must be a non-empty string')
      process.exit(1)
    }
  }
  const missing = enKeys.filter((key) => !(key in tables[locale]))
  if (missing.length > 0) {
    console.error('gen-locale: ' + locale + '.json is missing keys: ' + missing.join(', '))
    process.exit(1)
  }
  const extra = Object.keys(tables[locale]).filter((key) => !enKeys.includes(key))
  if (extra.length > 0) {
    console.error('gen-locale: ' + locale + '.json has keys English does not: ' + extra.join(', '))
    process.exit(1)
  }
}

const out = `/**
 * GENERATED by scripts/gen-locale.mjs -- do not edit.
 * Source of truth: locale/en.json, locale/ko.json and locale/zh.json.
 */
export const LOCALES = ${JSON.stringify(LOCALES)}
export const I18N = ${JSON.stringify(tables, null, 2)}
`
writeFileSync(join(root, 'lib', 'locale-table.js'), out)
console.log('gen-locale: wrote lib/locale-table.js (' + enKeys.length + ' keys x ' + LOCALES.length + ' locales)')
