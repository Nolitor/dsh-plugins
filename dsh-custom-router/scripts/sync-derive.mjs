#!/usr/bin/env node
/**
 * Mirror `lib/preset-derive.js` into the browser half.
 *
 * WHY A MIRROR AT ALL
 * The page loader evaluates `lib/client.js` as a plain script, so the browser
 * half cannot `import` the ESM derivation module. The mirror is therefore the
 * FEWEST copies that work: one canonical FILE (`lib/preset-derive.js`) and one
 * generated block in `lib/client.src.js`. Nothing is hand-maintained on the
 * page side — this script writes the block, and `checkDeriveMirror()` fails the
 * drift gate if the two ever diverge.
 *
 * Usage:
 *   node scripts/sync-derive.mjs           # rewrite the block
 *   node scripts/sync-derive.mjs --check   # verify only, exit 1 on drift
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { stripCode } from '../lib/preset-drift.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const CANONICAL = join(root, 'lib', 'preset-derive.js')
const CLIENT = join(root, 'lib', 'client.src.js')

const MIRROR_BEGIN = '// MIRROR-BEGIN'
const MIRROR_END = '// MIRROR-END'

const BEGIN = '    // ---- BEGIN DERIVED PRESET REGISTRY'
const END = '    // ---- END DERIVED PRESET REGISTRY'

/**
 * The canonical code, de-exported and re-indented for the factory body.
 * @returns {string} the block body.
 */
export function deriveBlockBody() {
  const canonical = readFileSync(CANONICAL, 'utf8')
  const start = canonical.indexOf(MIRROR_BEGIN)
  const stop = canonical.indexOf(MIRROR_END)
  if (start < 0 || stop < 0) throw new Error('sync-derive: lib/preset-derive.js has no MIRROR-BEGIN/MIRROR-END markers')
  return canonical
    .slice(start, stop)
    .replace(/^\/\/ MIRROR-BEGIN\n(?:\/\/.*\n)*/, '')
    .replace(/^export\s+(const|function)\b/gm, '$1')
    .trimEnd()
}

/**
 * The complete block, markers included.
 * @returns {string} the block.
 */
export function deriveBlock() {
  return [
    BEGIN + ' (mirrors lib/preset-derive.js) ------',
    '    //',
    '    // GENERATED by scripts/sync-derive.mjs — do not edit by hand. The page',
    '    // loader cannot import ESM, so the derivation is mirrored here;',
    '    // lib/preset-drift.js `checkDeriveMirror()` fails the gate on any drift.',
    '',
    deriveBlockBody(),
    '',
    END + ' ---------------------------------------',
  ].join('\n')
}

/** Find the current block. */
function locate(source) {
  const begin = source.indexOf(BEGIN)
  // Locate the END marker on its own line: the trailing dashes must not be
  // part of the search, or a second run appends them again.
  const end = source.indexOf(END, begin)
  if (begin < 0 || end < 0 || end < begin) throw new Error('sync-derive: lib/client.src.js has no DERIVED PRESET REGISTRY markers')
  return { begin, end: end + END.length }
}

if (process.argv[1] !== undefined && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  const source = readFileSync(CLIENT, 'utf8')
  const { begin, end } = locate(source)
  const wanted = deriveBlock()
  const current = source.slice(begin, end)
  if (process.argv.includes('--check')) {
    if (stripCode(current) !== stripCode(wanted)) {
      process.stderr.write('sync-derive: lib/client.src.js is STALE versus lib/preset-derive.js — run node scripts/sync-derive.mjs\n')
      process.exit(1)
    }
    process.stdout.write('sync-derive: current\n')
  } else if (current === wanted) {
    process.stdout.write('sync-derive: unchanged\n')
  } else {
    writeFileSync(CLIENT, source.slice(0, begin) + wanted + source.slice(end))
    process.stdout.write('sync-derive: wrote the derivation block into lib/client.src.js\n')
  }
}
