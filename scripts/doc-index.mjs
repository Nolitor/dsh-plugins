#!/usr/bin/env node
/**
 * Skeleton indexer for DSH Plugins documentation.
 *
 * Scans every tracked *.md (excluding bootcards/ and node_modules/), reads its
 * YAML-ish skeleton header (version / kind / status / updated / summary), and
 * writes:
 *   - INDEX.md            full table, grouped by kind
 *   - docs/SKELETON.md    compact one-line-per-doc skeleton (agent entry point)
 *
 * The header block is the contract. Files missing it are reported as MISSING so
 * doc drift is visible instead of silent.
 *
 * Run: node scripts/doc-index.mjs [--check]
 *   --check  exit 1 if any doc is missing a valid header or INDEX.md is stale
 */
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs'
import { join, relative } from 'node:path'

const root = new URL('..', import.meta.url).pathname
const SKIP_DIRS = new Set(['node_modules', '.git', '.runtime-measure', 'prototype-windows', 'prototype-harness', 'market', 'locale', 'test', 'lib', 'scripts', 'artifacts'])
const KINDS = ['rule', 'boot', 'spec', 'report', 'measurement', 'policy', 'readme', 'index']

/** Walk for *.md, skipping generated/vendor dirs and submodule trees we don't own. */
function findDocs(dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue
    const full = join(dir, entry.name)
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue
      if (entry.name.startsWith('dsh-')) continue // plugin tracks keep their own READMEs
      findDocs(full, out)
    } else if (entry.name.endsWith('.md')) out.push(full)
  }
  return out
}

/**
 * Parse the leading `<!-- skeleton: ... -->` block.
 * Format (one key per line, `key: value`):
 *   version, kind, status, updated, summary
 */
function parseSkeleton(text) {
  const match = text.match(/<!--\s*skeleton:([\s\S]*?)-->/)
  if (!match) return null
  const fields = {}
  for (const line of match[1].split('\n')) {
    const m = line.match(/^\s*([a-z-]+):\s*(.*)$/)
    if (m) fields[m[1]] = m[2].trim()
  }
  const required = ['version', 'kind', 'status', 'updated', 'summary']
  const missing = required.filter((k) => !fields[k])
  return missing.length ? { ...fields, __missing: missing } : fields
}

// Generated outputs are not source documents: exclude them from the scan.
const GENERATED = new Set(['INDEX.md', 'docs/SKELETON.md'])
const docs = findDocs(root).filter((f) => !GENERATED.has(relative(root, f))).sort()
const rows = []
for (const file of docs) {
  const rel = relative(root, file)
  const text = readFileSync(file, 'utf8')
  const skel = parseSkeleton(text)
  const lines = text.split('\n').length
  rows.push({ rel, lines, skeleton: skel, missing: skel?.__missing })
}

const bad = rows.filter((r) => !r.skeleton || r.missing)
const good = rows.filter((r) => r.skeleton && !r.missing)

// Boot cards are dated session cards: listed compactly, never in the main table.
const boot = good
  .filter((r) => r.rel.startsWith('bootcards/') && !r.rel.endsWith('/INDEX.md'))
  .sort((a, b) => b.rel.localeCompare(a.rel))
const nonBoot = good.filter((r) => !r.rel.startsWith('bootcards/'))

// --- docs/SKELETON.md : the compact agent-facing index -----------------------
const byKind = new Map()
for (const r of nonBoot) {
  const kind = KINDS.includes(r.skeleton.kind) ? r.skeleton.kind : 'other'
  if (!byKind.has(kind)) byKind.set(kind, [])
  byKind.get(kind).push(r)
}
const order = [...KINDS, 'other'].filter((k) => byKind.has(k))

let skeletonMd = `# Documentation Skeleton Index

> Generated by \`node scripts/doc-index.mjs\`. Do not edit by hand.
> One line per document: **version · kind · status · updated · summary**.
> Read this before opening any doc; open only the docs your task needs.

## Reading chain

\`\`\`
~/.dsh/AGENTS.md              global rules   (every session, auto-loaded)
  -> docs/RULES.md            detailed rules (this project, read on demand)
     -> docs/SKELETON.md      this index: what exists, what it covers
        -> bootcards/<ts>.md  dated session card (latest only, by default)
\`\`\`

`
for (const kind of order) {
  skeletonMd += `## ${kind}\n\n`
  for (const r of byKind.get(kind).sort((a, b) => b.skeleton.updated.localeCompare(a.skeleton.updated))) {
    const s = r.skeleton
    skeletonMd += `- **${s.version}** · ${s.status} · ${s.updated} · [${r.rel}](${relative(join(root, 'docs'), join(root, r.rel))})\n  ${s.summary}\n`
  }
  skeletonMd += '\n'
}
if (boot.length) {
  skeletonMd += `## boot (newest 5 of ${boot.length})\n\n`
  for (const r of boot.slice(0, 5)) {
    const s = r.skeleton
    skeletonMd += `- **${s.status}** · ${r.rel.replace('bootcards/', '')} · [card](${relative(join(root, 'docs'), join(root, r.rel))})\n  ${s.summary}\n`
  }
  skeletonMd += '\n'
}

if (bad.length) {
  skeletonMd += `## MISSING HEADER (${bad.length}) — fix before release\n\n`
  for (const r of bad) skeletonMd += `- [${r.rel}](${relative(join(root, 'docs'), join(root, r.rel))}) — missing: ${r.missing ? r.missing.join(', ') : 'entire skeleton block'}\n`
  skeletonMd += '\n'
}
skeletonMd += `---\n\n${good.length} indexed (${boot.length} boot cards), ${bad.length} missing header, ${docs.length} total.\n`

// --- INDEX.md : full table with size ----------------------------------------
let indexMd = `# Documentation Index

> Generated by \`node scripts/doc-index.mjs\`. Do not edit by hand.
> ${good.length} indexed / ${docs.length} documents. Compact view: [docs/SKELETON.md](docs/SKELETON.md).

| Version | Kind | Status | Updated | Lines | Document | Summary |
|---|---|---|---|---|---|---|
`
for (const r of nonBoot.sort((a, b) => a.rel.localeCompare(b.rel))) {
  const s = r.skeleton
  indexMd += `| ${s.version} | ${s.kind} | ${s.status} | ${s.updated} | ${r.lines} | [${r.rel}](${r.rel}) | ${s.summary} |\n`
}
if (bad.length) {
  indexMd += `\n### Missing skeleton header\n\n`
  for (const r of bad) indexMd += `- [${r.rel}](${r.rel}) — ${r.missing ? r.missing.join(', ') : 'no <!-- skeleton: --> block'}\n`
}

const check = process.argv.includes('--check')
if (check) {
  const stale = []
  for (const [file, next] of [[join(root, 'INDEX.md'), indexMd], [join(root, 'docs/SKELETON.md'), skeletonMd]]) {
    const prev = existsSync(file) ? readFileSync(file, 'utf8') : ''
    if (prev !== next) stale.push(relative(root, file))
  }
  if (bad.length) console.error(`FAIL: ${bad.length} doc(s) missing a skeleton header: ${bad.map((r) => r.rel).join(', ')}`)
  if (stale.length) console.error(`FAIL: stale index file(s): ${stale.join(', ')} — run npm run docs:index`)
  if (!bad.length && !stale.length) console.log(`OK: ${good.length} docs indexed, indexes up to date.`)
  process.exit(bad.length || stale.length ? 1 : 0)
}

writeFileSync(join(root, 'INDEX.md'), indexMd)
writeFileSync(join(root, 'docs/SKELETON.md'), skeletonMd)
console.log(`indexed ${good.length} docs, ${bad.length} missing header -> INDEX.md, docs/SKELETON.md`)
if (bad.length) for (const r of bad) console.log(`  MISSING: ${r.rel} (${r.missing ? r.missing.join(',') : 'no block'})`)
